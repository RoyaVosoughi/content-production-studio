export const STRINGS: Record<UiLanguage, Strings> = { en, fa };

/**
 * The interface text with the person's languages filled in: {language} is the content language on
 * screen, {other} the second one and {languages} all of them, each named in the interface language.
 */
export function localize(ui: UiLanguage, languages: readonly Language[], current?: Language): Strings {
  const shown = current ?? languages[0] ?? "en";
  const other = languages.find((code) => code !== shown) ?? shown;
  const names = languages.map((code) => languageName(code, ui));
  const values: Record<string, string> = {
    "{language}": languageName(shown, ui),
    "{other}": languageName(other, ui),
    "{languages}": names.join(ui === "fa" ? " و " : " and ") || languageName(shown, ui),
  };
  const fill = (value: unknown): unknown => {
    if (typeof value === "string") return value.replace(/\{(language|other|languages)\}/g, (token) => values[token]);
    if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, fill(item)]));
    return value;
  };
  return fill(STRINGS[ui]) as Strings;
}
